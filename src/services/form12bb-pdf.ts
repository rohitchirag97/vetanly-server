import PDFDocument from "pdfkit";

import type { DeclarationView } from "@/services/tax-declaration.services";

/**
 * Form 12BB: the employee's statement of claims to the employer for TDS (rule 26C). Built from the
 * declaration as it stands; the employee signs the verification on paper.
 */

// The built-in PDF fonts lack the rupee glyph, so amounts use "Rs.".
const money = (value: string | number) =>
  `Rs. ${Number(value).toLocaleString("en-IN", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

const CHAPTER_VI_A = ["80C", "80CCD1B", "80D_SELF", "80D_PARENTS", "80E", "80TTA"];

export const buildForm12bbPdf = (data: {
  organizationName: string;
  employeeName: string;
  pan: string | null;
  view: DeclarationView;
}): Promise<Buffer> =>
  new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: "A4", margin: 50 });
    const chunks: Buffer[] = [];
    doc.on("data", (chunk: Buffer) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    const left = doc.page.margins.left;
    const width = doc.page.width - left - doc.page.margins.right;
    const { view } = data;
    const declared = (sections: string[]) => view.items.filter((item) => sections.includes(item.section));

    const heading = (text: string) => {
      doc.moveDown(0.8).font("Helvetica-Bold").fontSize(11).fillColor("#000000").text(text, left);
      doc.moveDown(0.3);
    };
    const row = (label: string, value: string) => {
      const y = doc.y;
      doc.font("Helvetica").fontSize(10).text(label, left, y, { width: width * 0.62 });
      const after = doc.y;
      doc.text(value, left + width * 0.64, y, { width: width * 0.36, align: "right" });
      doc.y = Math.max(after, doc.y);
      doc.moveDown(0.25);
    };
    const none = () => doc.font("Helvetica-Oblique").fontSize(10).fillColor("#555555").text("Nil", left).fillColor("#000000");

    doc.font("Helvetica-Bold").fontSize(15).text("FORM NO. 12BB", { align: "center" });
    doc.font("Helvetica").fontSize(9).text("(See rule 26C)", { align: "center" });
    doc.moveDown(0.3).fontSize(10).text("Statement showing particulars of claims by an employee for deduction of tax", { align: "center" });
    doc.moveDown();

    row("Name of the employee", data.employeeName);
    row("PAN of the employee", data.pan ?? "Not on file");
    row("Employer", data.organizationName);
    row("Financial year", view.financialYear);
    row("Tax regime chosen", view.declaration?.taxRegime === "old" ? "Old regime" : "New regime (section 115BAC)");

    heading("1. House rent allowance");
    const rent = declared(["HRA"]);
    if (rent.length === 0) none();
    for (const item of rent) {
      row("Rent paid to the landlord (year)", money(item.declaredAmount));
      row("Name of the landlord", String(item.details.landlordName ?? "-"));
      row("Address of the landlord", String(item.details.landlordAddress ?? "-"));
      row("PAN of the landlord", String(item.details.landlordPan || "Not required (rent up to Rs. 1,00,000)"));
    }

    heading("2. Leave travel concession");
    none();

    heading("3. Deduction of interest on borrowing (section 24)");
    const loans = declared(["24B"]);
    if (loans.length === 0) none();
    for (const item of loans) {
      row("Interest payable to the lender", money(item.declaredAmount));
      row("Name of the lender", String(item.details.lenderName ?? "-"));
      row("PAN of the lender", String(item.details.lenderPan || "-"));
    }

    heading("4. Deductions under Chapter VI-A");
    const deductions = declared(CHAPTER_VI_A);
    if (deductions.length === 0) none();
    for (const item of deductions) {
      row(`${item.sectionLabel}: ${item.kindLabel}${item.description ? ` (${item.description})` : ""}`, money(item.declaredAmount));
    }

    const previous = declared(["PREVIOUS_EMPLOYER"]);
    if (previous.length > 0) {
      heading("Income from a previous employer during the year");
      for (const item of previous) {
        row(`Salary from ${item.details.employerName ?? "previous employer"}`, money(item.declaredAmount));
        row("Tax deducted by that employer", money(Number(item.details.tdsDeducted ?? 0)));
      }
    }

    heading("Verification");
    doc.font("Helvetica").fontSize(10).text(
      `I, ${data.employeeName}, do hereby certify that the information given above is complete and correct.`,
      left,
      doc.y,
      { width },
    );
    doc.moveDown(2.5);
    row("Place: ____________________", "Signature of the employee");
    row("Date: _____________________", "");
    doc.moveDown(2);
    doc.font("Helvetica").fontSize(8).fillColor("#777777").text(
      "Generated by Vetanly from the employee's declaration. Amounts are as declared; verified amounts may differ.",
      left,
      doc.y,
      { width, align: "center" },
    );
    doc.end();
  });
